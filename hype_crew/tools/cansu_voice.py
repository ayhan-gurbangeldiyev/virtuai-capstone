def _sanitize_em_dash(content: str) -> str:
    """Strip em-dash (—) and en-dash (–) from writer output. Replace with
    comma. Idempotent.
    """
    if not content:
        return content
    return content.replace("—", ",").replace("–", ",")


_HASHTAG_RE = re.compile(r"#\w+")


def _strip_all_hashtags(content: str) -> str:
    """Remove every #word from content. Preserves surrounding punctuation
    sensibly by collapsing runs of whitespace + stray separators. Idempotent.
    """
    if not content:
        return content
    out = _HASHTAG_RE.sub("", content)
    out = re.sub(r"[ \t]{2,}", " ", out)
    out = re.sub(r"\n{3,}", "\n\n", out)
    out = re.sub(r"\s+([.,;:!?])", r"\1", out)
    out = re.sub(r"\n[ \t]*[-•·][ \t]*\n", "\n\n", out)
    return out.strip()


_EMOJI_RE = re.compile(
    "["
    "\U0001F300-\U0001F5FF"  # symbols & pictographs
    "\U0001F600-\U0001F64F"  # emoticons
    "\U0001F680-\U0001F6FF"  # transport & map symbols
    "\U0001F700-\U0001F77F"
    "\U0001F780-\U0001F7FF"
    "\U0001F800-\U0001F8FF"
    "\U0001F900-\U0001F9FF"  # supplemental symbols & pictographs
    "\U0001FA00-\U0001FA6F"
    "\U0001FA70-\U0001FAFF"
    "\U00002600-\U000026FF"  # misc symbols
    "\U00002700-\U000027BF"  # dingbats
    "\U0001F1E6-\U0001F1FF"  # regional indicators
    "\U0000200D"             # zero-width joiner
    "\U0000FE0F"             # variation selector-16
    "]+",
    flags=re.UNICODE,
)


def _strip_emojis(content: str) -> str:
    if not content:
        return content
    out = _EMOJI_RE.sub("", content)
    out = re.sub(r"[ \t]{2,}", " ", out)
    return out.strip()


_PERSONA_DISCLOSURE_RES = [
    re.compile(r"[-—–]\s*Cansu,\s*AI\s*persona[^\n]*", re.IGNORECASE),
    re.compile(r"AI[\s-]*persona\s+by\s+VirtuAI[^\n]*", re.IGNORECASE),
    re.compile(r"\bAI[\s-]*generated\b[^\n]*", re.IGNORECASE),
    re.compile(r"\bThis (article|content|post) is generated by[^\n]+", re.IGNORECASE),
]


def _strip_persona_disclosure(content: str) -> str:
    if not content:
        return content
    out = content
    for r in _PERSONA_DISCLOSURE_RES:
        out = r.sub("", out)
    out = re.sub(r"\n{3,}", "\n\n", out)
    return out.strip()


# Per-platform hard length spec (Phase 35.3 + Phase 37).
_PLATFORM_LENGTH_SPEC: dict[str, dict[str, int]] = {
    "twitter": {"min": 80,   "max": 280},
    "x":       {"min": 80,   "max": 280},
    "linkedin":{"min": 300,  "max": 500},
    "devto":   {"min": 1400, "max": 3500},
    "blog":    {"min": 1400, "max": 5000},
    "instagram":{"min": 150, "max": 2200},
    "youtube": {"min": 100,  "max": 1000},
}


def _enforce_platform_length(content: str, platform: str) -> str:
    """Phase 35.3 — Sentence-aware hard truncate when content exceeds the
    platform's max char cap. Logs a warning when it falls below the soft
    min (no truncation — too short means re-generate via prompt iteration).
    """
    plat = platform.lower()
    spec = _PLATFORM_LENGTH_SPEC.get(plat)
    if not spec:
        return content

    n = len(content)
    if n < spec["min"]:
        logger.warning(
            f"[length] {plat} content {n} chars < min {spec['min']} "
            f"— prompt may be undersizing; not truncating"
        )
        return content

    if n <= spec["max"]:
        return content

    target = spec["max"]
    trimmed = content[:target].rstrip()

    # 2026-06-11 — markdown-aware kesim. Eski mantık başlık satırında kesip
    # nokta ekleyebiliyordu ("## Ne Yapıyor?" → "## Ne Yapıyor?.") ve makaleyi
    # cümle ortasında bitirebiliyordu. Yeni öncelik sırası:
    #   1) paragraf sınırı (\n\n) — markdown yapısı bozulmaz
    #   2) cümle sınırı (. ! ? …)
    #   3) kelime sınırı (son çare)
    # Her durumda: sonda yarım kalan başlık satırı atılır; "?!…" ile biten
    # metne nokta EKLENMEZ; başlık satırına asla nokta eklenmez.
    last_para = trimmed.rfind("\n\n")
    last_sentence_end = max(
        trimmed.rfind("."),
        trimmed.rfind("!"),
        trimmed.rfind("?"),
        trimmed.rfind("…"),
    )
    if "\n" in content and last_para >= int(target * 0.5):
        trimmed = trimmed[:last_para].rstrip()
    elif last_sentence_end >= int(target * 0.6):
        trimmed = trimmed[: last_sentence_end + 1]
    elif " " in trimmed:
        trimmed = trimmed.rsplit(" ", 1)[0].rstrip(",.;:!?-")
        if not trimmed.endswith((".", "!", "?", "…")):
            trimmed += "."

    # Sonda yarım/çıplak kalmış markdown başlığı varsa at (başlığın altı
    # kesilmişse başlık tek başına sarkar).
    _lines = trimmed.rstrip().split("\n")
    while _lines and _lines[-1].lstrip().startswith("#"):
        _lines.pop()
    trimmed = "\n".join(_lines).rstrip()

    logger.warning(
        f"[length] {plat} content truncated {n} → {len(trimmed)} chars "
        f"(max {target})"
    )
    return trimmed


def sanitize_draft(content: str, platform: str) -> str:
    """Berkay sanitize zinciri — tek çağrı. Sıra önemli."""
    content = _sanitize_em_dash(content)
    content = _strip_all_hashtags(content)
    content = _strip_emojis(content)
    content = _strip_persona_disclosure(content)
    content = _enforce_platform_length(content, platform)
    return content


