# Kaynak birleşimi — gate ↔ yazar simetrisinin TEK tanımı (2026-06-10).
# Tarihçe: a96e9e3 union'ı yazar+gate'e eşitledi; 2026-06-09 prod hotfix'i
# gate'i full_source_text'e öncelikledi (source_tweets[].text 200ch'de
# kırpılıyor) ama full_source_text bazı trendlerde tweet'leri İÇERMİYOR
# (Apple Siri vakası: "Apple Intelligence" yalnız tweet union'ında).
# Sonuç: yazar union gördü, gate fst gördü → deterministik false block.
# Çözüm: HER İKİSİ — fst + raw_content + tüm tweet text'leri tek birleşim.
# ────────────────────────────────────────────────────────────────────────────

def assemble_source_text(trend_row: Optional[dict]) -> str:
    """trends satırından (full_source_text, raw_content, source_tweets
    alanlarıyla) gate ve yazarın ortak göreceği kaynak metni birleştirir.
    Eksik alanlar sessizce atlanır; sıra: fst → raw → tweet metinleri.
    """
    if not isinstance(trend_row, dict):
        return ""
    parts: list[str] = []
    fst = (trend_row.get("full_source_text") or "").strip()
    if fst:
        parts.append(fst)
    rc = (trend_row.get("raw_content") or "").strip()
    if rc and rc not in fst:
        parts.append(rc)
    for st in (trend_row.get("source_tweets") or []):
        if isinstance(st, dict) and st.get("text"):
            t = str(st["text"]).strip()
            if t and t not in fst:
                parts.append(t)
    return "\n\n".join(parts)
